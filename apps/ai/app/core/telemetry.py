"""Prometheus metrics collector and PII-safe structured telemetry for apps/ai."""

from __future__ import annotations

import re
from dataclasses import dataclass, field


@dataclass
class AiMetricsRegistry:
    requests_total: dict[str, int] = field(default_factory=dict)
    llm_calls_total: dict[str, int] = field(default_factory=dict)
    tokens_in_total: int = 0
    tokens_out_total: int = 0
    cost_usd_total: float = 0.0
    cache_hits_total: int = 0
    cache_misses_total: int = 0
    last_groundedness_score: float = 1.0
    last_citation_precision: float = 1.0

    def record_request(self, endpoint: str) -> None:
        self.requests_total[endpoint] = self.requests_total.get(endpoint, 0) + 1

    def record_llm_call(
        self,
        model: str,
        tokens_in: int,
        tokens_out: int,
        cost_usd: float,
        cache_hit: bool,
    ) -> None:
        self.llm_calls_total[model] = self.llm_calls_total.get(model, 0) + 1
        self.tokens_in_total += tokens_in
        self.tokens_out_total += tokens_out
        self.cost_usd_total += cost_usd
        if cache_hit:
            self.cache_hits_total += 1
        else:
            self.cache_misses_total += 1

    def render_prometheus(self) -> str:
        lines: list[str] = [
            "# HELP jono_ai_tokens_in_total Total input tokens processed by AI gateway",
            "# TYPE jono_ai_tokens_in_total counter",
            f"jono_ai_tokens_in_total {self.tokens_in_total}",
            "# HELP jono_ai_tokens_out_total Total output tokens generated by AI gateway",
            "# TYPE jono_ai_tokens_out_total counter",
            f"jono_ai_tokens_out_total {self.tokens_out_total}",
            "# HELP jono_ai_cost_usd_total Estimated cumulative LLM cost in USD",
            "# TYPE jono_ai_cost_usd_total counter",
            f"jono_ai_cost_usd_total {self.cost_usd_total:.6f}",
            "# HELP jono_ai_cache_hits_total Semantic response cache hits",
            "# TYPE jono_ai_cache_hits_total counter",
            f"jono_ai_cache_hits_total {self.cache_hits_total}",
            "# HELP jono_ai_cache_misses_total Semantic response cache misses",
            "# TYPE jono_ai_cache_misses_total counter",
            f"jono_ai_cache_misses_total {self.cache_misses_total}",
            "# HELP jono_ai_groundedness_score Latest RAG evaluation groundedness score",
            "# TYPE jono_ai_groundedness_score gauge",
            f"jono_ai_groundedness_score {self.last_groundedness_score:.4f}",
            "# HELP jono_ai_citation_precision Latest RAG evaluation citation precision",
            "# TYPE jono_ai_citation_precision gauge",
            f"jono_ai_citation_precision {self.last_citation_precision:.4f}",
        ]
        for endpoint, count in sorted(self.requests_total.items()):
            safe_ep = endpoint.replace('"', "")
            lines.append(f'jono_ai_requests_total{{endpoint="{safe_ep}"}} {count}')
        return "\n".join(lines) + "\n"


metrics_registry = AiMetricsRegistry()

_BD_PHONE_RE = re.compile(r"(?:\+?88)?01[3-9]\d{8}")
_EMAIL_RE = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")
_ID_NUM_RE = re.compile(r"\b\d{10}(?:\d{3}|\d{7})?\b")
_CARD_RE = re.compile(r"\b(?:\d[ -]*?){13,16}\b")


def redact_pii_text(text: str) -> tuple[str, list[str]]:
    """Redacts Bangladesh phones, emails, NID/BRN numbers, and payment cards before logging."""
    found: list[str] = []
    out = text
    if _BD_PHONE_RE.search(out):
        found.append("phone_bd")
        out = _BD_PHONE_RE.sub("[REDACTED_PHONE]", out)
    if _EMAIL_RE.search(out):
        found.append("email")
        out = _EMAIL_RE.sub("[REDACTED_EMAIL]", out)
    if _CARD_RE.search(out):
        found.append("card_or_long_number")
        out = _CARD_RE.sub("[REDACTED_NUMBER]", out)
    if _ID_NUM_RE.search(out):
        found.append("nid_or_brn")
        out = _ID_NUM_RE.sub("[REDACTED_ID]", out)
    return out, found
